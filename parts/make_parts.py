"""Generate printable STL files for Pip, the desk robot.

Run:  .venv/bin/python parts/make_parts.py
Output: stl/*.stl  (units: millimetres, Z is up, each part already in its print orientation)

Coordinates used while modelling (before each part is turned for printing):
  x = right, y = front, z = up. Body floor sits at z = 0.
All key sizes live in the constants below, so you can tweak and re-run.
"""
from pathlib import Path
import struct
import numpy as np
from manifold3d import Manifold

OUT = Path(__file__).resolve().parent.parent / "stl"
SEG = 48  # roundness of curves

# ---------- sizes (mm) ----------
WALL = 2.0
BODY = (70.0, 56.0, 55.0)       # width, depth, height
BODY_R = 10.0
HEAD = (62.0, 48.0, 50.0)
HEAD_R = 12.0

# SG90 micro servo
SERVO_W, SERVO_L = 12.4, 22.8    # window size (body + 0.2 mm play)
SERVO_SHAFT_OFF = 5.9            # shaft distance from servo centre, along its length
SERVO_TAB_PITCH = 27.5           # distance between the two tab screw holes
SERVO_TAB_DROP = 4.5             # tabs sit this far below the servo's top face

ARM_SHAFT = (4.0, 40.0)          # (y, z) of the arm servo shafts on the body sides
NECK_DISC = (60.0, 66.0)         # z range of the pan turntable
HEAD_BOTTOM = 72.0               # z of the head's underside (body coords)
TILT_AXIS_IN_HEAD = 24.0         # tilt axis height above head underside

DISPLAY_WIN = (32.8, 28.2, 4.0)  # 1.69" ST7789 active area (landscape) + corner radius
DISPLAY_PANEL = (38.0, 30.6)     # panel outline the frame holds

SPLIT = 8.0                      # depth of the back-cover and face-bezel "trays"
SCREW_PILOT = 1.8                # M2 self-tapping pilot hole
SCREW_CLEAR = 2.4


# ---------- helpers ----------
def box(x0, x1, y0, y1, z0, z1):
    return Manifold.cube([x1 - x0, y1 - y0, z1 - z0]).translate([x0, y0, z0])


def rbox(size, r, center=(0, 0, 0)):
    """Box with all edges rounded by r (hull of 8 spheres)."""
    sx, sy, sz = (s / 2 - r for s in size)
    ball = Manifold.sphere(r, SEG)
    pts = [ball.translate([cx * sx, cy * sy, cz * sz])
           for cx in (-1, 1) for cy in (-1, 1) for cz in (-1, 1)]
    return Manifold.batch_hull(pts).translate(list(center))


def cyl(r, h, axis="z", at=(0, 0, 0), seg=SEG):
    """Cylinder of radius r, length h, centred on `at`, along the given axis."""
    c = Manifold.cylinder(h, r, r, seg).translate([0, 0, -h / 2])
    if axis == "x":
        c = c.rotate([0, 90, 0])
    elif axis == "y":
        c = c.rotate([90, 0, 0])
    return c.translate(list(at))


def rrect_plate(w, h, r, t, at, axis="y"):
    """Rounded rectangle plate of thickness t, its face normal along `axis`."""
    pts = [cyl(r, t, "z", (sx * (w / 2 - r), sy * (h / 2 - r), 0), 32)
           for sx in (-1, 1) for sy in (-1, 1)]
    p = Manifold.batch_hull(pts)
    if axis == "y":
        p = p.rotate([90, 0, 0])
    elif axis == "x":
        p = p.rotate([0, 90, 0])
    return p.translate(list(at))


def union(parts):
    return Manifold.batch_boolean(parts, __import__("manifold3d").OpType.Add)


ASSEMBLED = {}  # name -> part in assembled position (body coords), for the 3D viewer


def keep(m: Manifold, name: str, print_rot, place=None):
    """Save the part as an STL in print orientation and remember it in assembled position."""
    save_stl(m.rotate(print_rot), name)
    ASSEMBLED[name] = place(m) if place else m


def export_viewer_data(path: Path):
    import base64, json
    data = {}
    for name, m in ASSEMBLED.items():
        mesh = m.to_mesh()
        v = np.asarray(mesh.vert_properties, dtype=np.float32)[:, :3]
        v = np.stack([-v[:, 0], v[:, 2], v[:, 1]], 1).astype(np.float32)  # to three.js: y up, front = +z
        t = np.asarray(mesh.tri_verts, dtype=np.uint32)
        data[name] = {"pos": base64.b64encode(v.tobytes()).decode(),
                      "idx": base64.b64encode(t.tobytes()).decode()}
    path.write_text("// generated by parts/make_parts.py, do not edit\nwindow.PIP_PARTS = "
                    + json.dumps(data) + ";\n")
    print(f"  viewer data -> {path.name} ({path.stat().st_size / 1e6:.1f} MB)")


def save_stl(m: Manifold, name: str):
    mesh = m.to_mesh()
    v = np.asarray(mesh.vert_properties)[:, :3]
    t = np.asarray(mesh.tri_verts)
    # sit the part on the build plate, centred
    lo, hi = v.min(0), v.max(0)
    v = v - [(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, lo[2]]
    tri = v[t]
    n = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-12
    path = OUT / f"{name}.stl"
    with open(path, "wb") as f:
        f.write(b"Pip desk robot".ljust(80, b" "))
        f.write(struct.pack("<I", len(t)))
        rec = np.zeros(len(t), dtype=[("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
        rec["n"], rec["v"] = n, tri
        f.write(rec.tobytes())
    size = hi - lo
    print(f"  {name:14s} {size[0]:5.1f} x {size[1]:5.1f} x {size[2]:5.1f} mm   "
          f"{m.volume() / 1000:5.1f} cm³")


def servo_window(center, along, normal):
    """Rectangular hole for an SG90 plus its 2 tab screw holes.
    center: servo body centre on the wall; along: axis of servo length; normal: wall normal."""
    cx, cy, cz = center
    L, W, deep = SERVO_L, SERVO_W, 12.0
    dims = {"x": 0, "y": 0, "z": 0}
    dims[along] = L
    dims[normal] = deep
    other = ({"x", "y", "z"} - {along, normal}).pop()
    dims[other] = W
    win = Manifold.cube([dims["x"], dims["y"], dims["z"]], True).translate([cx, cy, cz])
    holes = []
    for s in (-1, 1):
        p = [cx, cy, cz]
        p["xyz".index(along)] += s * SERVO_TAB_PITCH / 2
        holes.append(cyl(SCREW_PILOT / 2, deep, normal, tuple(p), 16))
    return union([win] + holes)


def screw_column(x, z, y_from, y_to, chamfer_dir, wall_x):
    """Screw post running along y, widened until it touches the side wall at wall_x,
    with a 45° chamfer under it so it prints without support."""
    x0, x1 = min(x - 3, wall_x), max(x + 3, wall_x)
    col = box(x0, x1, min(y_from, y_to), max(y_from, y_to), z - 3, z + 3)
    yt = y_to + chamfer_dir * 6
    sliver = box(min(wall_x, wall_x - 0.4 * (1 if wall_x > 0 else -1)), max(wall_x, wall_x - 0.4 * (1 if wall_x > 0 else -1)),
                 yt - 0.2, yt + 0.2, z - 3, z + 3)
    return Manifold.batch_hull([col, sliver])


# ---------- parts ----------
def body_parts():
    W, D, H = BODY
    outer = rbox(BODY, BODY_R, (0, 0, H / 2))
    inner = rbox((W - 2 * WALL, D - 2 * WALL, H - 2 * WALL), BODY_R - WALL, (0, 0, H / 2))
    back_y = -D / 2 + SPLIT  # split plane between body and back cover
    hollow = outer - inner
    back = box(-60, 60, -60, back_y, -10, 90)
    shell = hollow - back

    # screw columns at the 4 back corners (screws come in from the back cover)
    xi = W / 2 - 6
    screw_pts = [(sx * xi, z) for sx in (-1, 1) for z in (7, H - 7)]
    cols = [screw_column(x, z, back_y, back_y + 12, +1, (W / 2 - WALL + 0.5) * (1 if x > 0 else -1))
            for x, z in screw_pts]
    shell = union([shell] + cols) ^ outer
    for x, z in screw_pts:
        shell -= cyl(SCREW_PILOT / 2, 20, "y", (x, back_y + 8, z), 16)

    # pan servo in the ceiling: shaft at (0, 0), servo body runs toward the back
    shell -= servo_window((0, -SERVO_SHAFT_OFF, H), "y", "z")
    shell -= cyl(4.5, 12, "z", (14, -12, H))  # cable hole for head wires

    # arm servos in the side walls: long axis vertical, shaft at the top end
    ay, az = ARM_SHAFT
    for sx in (-1, 1):
        shell -= servo_window((sx * W / 2, ay, az - SERVO_SHAFT_OFF), "z", "x")

    # speaker grille (20 mm speaker) on the front, lower half
    holes = []
    for row in range(-3, 4):
        for col in range(-3, 4):
            px, pz = col * 3.2 + (1.6 if row % 2 else 0), row * 2.8
            if px * px + pz * pz <= 9.5 ** 2:
                holes.append(cyl(1.15, 10, "y", (px, D / 2, 18 + pz), 16))
    shell -= union(holes)

    # back cover = the slice we removed, with screw, USB-C and switch holes
    cover = union([hollow ^ back] + [box(x - 3, x + 3, -D / 2 + 1, back_y, z - 3, z + 3)
                                     for x, z in screw_pts]) ^ outer
    for x, z in screw_pts:
        cover -= cyl(SCREW_CLEAR / 2, 30, "y", (x, back_y, z), 16)
        cover -= cyl(2.3, 1.2, "y", (x, -D / 2 + 0.6, z), 24)  # shallow countersink
    cy = -D / 2 + 1
    cover -= rrect_plate(10.0, 4.0, 1.6, 6, (0, cy, 10), "y")    # USB-C charge port
    cover -= rrect_plate(9.0, 4.5, 0.5, 6, (17, cy, 10), "y")    # slide power switch
    for i in range(-2, 3):                                       # vent slots
        cover -= rrect_plate(14, 2, 1, 6, (0, cy, 38 + i * 4), "y")

    # print orientation: body front-face down (open back faces up, no ceiling to bridge)
    keep(shell, "body_shell", [90, 0, 0])
    keep(cover, "back_cover", [-90, 0, 0])


def head_parts():
    W, D, H = HEAD
    outer = rbox(HEAD, HEAD_R, (0, 0, H / 2))
    inner = rbox((W - 2 * WALL, D - 2 * WALL, H - 2 * WALL), HEAD_R - WALL, (0, 0, H / 2))
    front_y = D / 2 - SPLIT  # split plane between head and face bezel
    front_cut = box(-60, 60, front_y, 60, -10, 90)
    hollow = outer - inner
    shell = hollow - front_cut

    xi = W / 2 - 6
    screw_pts = [(sx * xi, z) for sx in (-1, 1) for z in (7, H - 7)]
    cols = [screw_column(x, z, front_y, front_y - 10, -1, (W / 2 - WALL + 0.5) * (1 if x > 0 else -1))
            for x, z in screw_pts]

    # tilt servo cradle: upright plate with an SG90 window, shaft points to -x
    zt = TILT_AXIS_IN_HEAD
    case_top_x = 1.5 + 4.0                    # horn face at x=1.5, horn ~4 mm above case
    plate_x0 = case_top_x + SERVO_TAB_DROP    # tabs rest against this face
    cradle = box(plate_x0, plate_x0 + 3, -12, 12, WALL - 0.5, zt + 12)
    cradle -= servo_window((plate_x0 + 1.5, 0, zt - SERVO_SHAFT_OFF), "z", "x")
    shell = union([shell, cradle] + cols) ^ outer
    for x, z in screw_pts:
        shell -= cyl(SCREW_PILOT / 2, 20, "y", (x, front_y - 6, z), 16)

    # floor slot for the neck fin (lets the head nod about ±15°) + cable pass
    shell -= box(-4, 3, -15, 15, -5, WALL + 1)
    # side holes for the ear pegs, top hole for the antenna
    for sx in (-1, 1):
        shell -= cyl(2.1, 10, "x", (sx * W / 2, -2, H * 0.58), 24)
    shell -= cyl(2.1, 10, "z", (8, -4, H), 24)

    # face bezel = removed front slice, with display window and a frame that holds the panel
    bezel = union([hollow ^ front_cut] + [box(x - 3, x + 3, front_y, D / 2 - 1, z - 3, z + 3)
                                          for x, z in screw_pts]) ^ outer
    ww, wh, wr = DISPLAY_WIN
    bezel -= rrect_plate(ww, wh, wr, 10, (0, D / 2, H / 2 + 1), "y")
    pw, ph = DISPLAY_PANEL
    front_y = D / 2 - WALL  # the panel frame hangs off the inside of the face plate
    frame = box(-pw / 2 - 1.5, pw / 2 + 1.5, front_y - 3, front_y + 0.1, H / 2 + 1 - ph / 2 - 1.5,
                H / 2 + 1 + ph / 2 + 1.5)
    frame -= box(-pw / 2, pw / 2, front_y - 5, front_y + 1, H / 2 + 1 - ph / 2, H / 2 + 1 + ph / 2)
    frame -= box(-6, 6, front_y - 5, front_y + 1, H / 2 + 1 - ph / 2 - 3, H / 2)  # ribbon cable gap
    bezel = (bezel + frame) ^ outer
    for x, z in screw_pts:
        bezel -= cyl(SCREW_CLEAR / 2, 30, "y", (x, D / 2, z), 16)
        bezel -= cyl(2.3, 1.2, "y", (x, D / 2 - 0.6, z), 24)

    # print: head back-face down (open front faces up); bezel face down
    up = lambda m: m.translate([0, 0, HEAD_BOTTOM])
    keep(shell, "head_shell", [-90, 0, 0], up)
    keep(bezel, "face_bezel", [90, 0, 0], up)


def horn_pocket(depth):
    """Recess for an SG90 cross horn (2 crossed arms + hub), cut from z=0 upward."""
    hub = cyl(3.8, depth * 2, "z", (0, 0, 0))
    a1 = box(-10.5, 10.5, -2.6, 2.6, -depth, depth)
    a2 = box(-2.6, 2.6, -8.5, 8.5, -depth, depth)
    return union([hub, a1, a2])


def neck():
    # turntable disc sits on the pan servo horn; fin carries the head's tilt horn
    d0, d1 = NECK_DISC
    disc = cyl(13, d1 - d0, "z", (0, 0, (d1 - d0) / 2))
    disc -= horn_pocket(2.0)
    disc -= cyl(1.2, 20, "z", (0, 0, 0), 16)
    axis_local = HEAD_BOTTOM + TILT_AXIS_IN_HEAD - d0
    fin = box(-2.5, 1.5, -7, 7, d1 - d0 - 0.5, axis_local + 6)
    fin -= cyl(1.1, 10, "x", (0, 0, axis_local), 16)                  # horn screw
    fin -= cyl(3.8, 2.0, "x", (1.5, 0, axis_local))                   # single-horn hub recess
    fin -= box(0.5, 2.6, -2.4, 2.4, axis_local - 15, axis_local)      # horn arm slot (points down)
    # gussets so the fin is stiff
    g = Manifold.batch_hull([box(-2.5, 1.5, -11, 11, d1 - d0 - 0.5, d1 - d0),
                             box(-2.5, 1.5, -7, 7, d1 - d0 + 6, d1 - d0 + 6.5)])
    keep(union([disc, fin, g]), "neck", [0, 0, 0], lambda m: m.translate([0, 0, d0]))


def arm():
    shoulder = Manifold.sphere(7.5, SEG).scale([0.62, 1, 1])
    hand = Manifold.sphere(6.0, SEG).scale([0.62, 1, 1]).translate([0, 5, -24])
    a = Manifold.batch_hull([shoulder, hand])
    a = a - box(-20, -2.6, -30, 30, -40, 20)        # flat inner face (sits on the bed)
    a = a.translate([2.6, 0, 0])                      # inner face now at x = 0
    a -= horn_pocket(2.0).rotate([0, 90, 0]) ^ box(-0.1, 2.0, -20, 20, -20, 20)
    a -= cyl(1.15, 30, "x", (0, 0, 0), 16)          # horn screw
    a -= cyl(2.3, 2.0, "x", (6.0, 0, 0), 24)        # screw head recess on the outside
    save_stl(a.rotate([0, -90, 0]), "arm_x2")
    face_x = BODY[0] / 2 + (SERVO_TAB_DROP - WALL) + 4.0  # servo case pokes out, horn adds ~4 mm
    ay, az = ARM_SHAFT
    ASSEMBLED["arm_r"] = a.translate([face_x, ay, az])
    ASSEMBLED["arm_l"] = a.mirror([1, 0, 0]).translate([-face_x, ay, az])


def ear():
    e = cyl(8, 4, "z", (0, 0, 2)) - cyl(5, 2, "z", (0, 0, 4))  # dish
    e = e + cyl(4.5, 1.5, "z", (0, 0, 3.25))
    peg = cyl(1.95, 4, "z", (0, 0, -2), 24)
    e = union([e, peg])
    save_stl(e.rotate([180, 0, 0]), "ear_x2")
    W, D, H = HEAD
    ASSEMBLED["ear_r"] = e.rotate([0, 90, 0]).translate([W / 2, -2, HEAD_BOTTOM + H * 0.58])
    ASSEMBLED["ear_l"] = e.rotate([0, -90, 0]).translate([-W / 2, -2, HEAD_BOTTOM + H * 0.58])


def antenna():
    post = cyl(1.95, 18, "z", (0, 0, 9), 24)
    ball = Manifold.sphere(4.5, SEG).translate([0, 0, 19])
    keep(post + ball, "antenna", [0, 0, 0],
         lambda m: m.translate([8, -4, HEAD_BOTTOM + HEAD[2] - 4]))


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    print("Writing STL files to", OUT)
    body_parts()
    head_parts()
    neck()
    arm()
    ear()
    antenna()
    export_viewer_data(Path(__file__).resolve().parent.parent / "viewer" / "parts-data.js")
